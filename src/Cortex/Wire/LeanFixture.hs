{- | Contract registry for the record-form phantom fixture: the nominal
record shape of @Pair@ must be declared for record @*@ lowering.
-}
recordScatterEnv :: WireCompileEnv
recordScatterEnv =
  emptyWireCompileEnv
    { wireCompileEnvContractRegistry =
        Just
          ( wireContractRegistryFromList
              [ jsonContract "A"
              , jsonContract "B"
              , jsonContract "Done"
              , (jsonContract "Pair")
                  { wireContractSpecRecordFields =
                      Just
                        ( Map.fromList
                            [ ("a", ContractId "A")
                            , ("b", ContractId "B")
                            ]
                        )
                  }
              ]
          )
    }
  where
    jsonContract contractId =
      WireContractSpec
        { wireContractSpecId = contractId
        , wireContractSpecPayloadKind = WirePayloadJson
        , wireContractSpecDescription = contractId
        , wireContractSpecRecordFields = Nothing
        , wireContractSpecSchema = Nothing
        , wireContractSpecExamples = []
        }
